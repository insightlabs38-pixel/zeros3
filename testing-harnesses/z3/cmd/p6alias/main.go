// Command p6alias regenerates a research package's re-export file for a core package:
// every exported package-level declaration of the core becomes an alias (types), a const
// or a var/func value forward, so research drivers keep compiling while the algorithms
// live in the stdlib-only core.   usage: p6alias CORE_DIR CORE_IMPORT PKG OUT.go [SKIP...]
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"sort"
	"strings"
)

func main() {
	dir, imp, pkg, out := os.Args[1], os.Args[2], os.Args[3], os.Args[4]
	skip := map[string]bool{}
	for _, n := range os.Args[5:] {
		skip[n] = true
	}
	fset := token.NewFileSet()
	pk, err := parser.ParseDir(fset, dir, func(fi os.FileInfo) bool { return !strings.HasSuffix(fi.Name(), "_test.go") }, 0)
	if err != nil {
		panic(err)
	}
	last := imp[strings.LastIndex(imp, "/")+1:]
	var types, consts, vars, funcs []string
	for _, p := range pk {
		for _, f := range p.Files {
			for _, d := range f.Decls {
				switch d := d.(type) {
				case *ast.FuncDecl:
					if d.Recv == nil && d.Name.IsExported() && d.Type.TypeParams == nil {
						funcs = append(funcs, d.Name.Name)
					}
				case *ast.GenDecl:
					for _, s := range d.Specs {
						switch s := s.(type) {
						case *ast.TypeSpec:
							if s.Name.IsExported() && s.TypeParams == nil {
								types = append(types, s.Name.Name)
							}
						case *ast.ValueSpec:
							for _, n := range s.Names {
								if n.IsExported() {
									if d.Tok == token.CONST {
										consts = append(consts, n.Name)
									} else {
										vars = append(vars, n.Name)
									}
								}
							}
						}
					}
				}
			}
		}
	}
	for _, l := range [][]string{types, consts, vars, funcs} {
		sort.Strings(l)
	}
	filt := func(l []string) []string {
		var o []string
		for _, n := range l {
			if !skip[n] {
				o = append(o, n)
			}
		}
		return o
	}
	types, consts, vars, funcs = filt(types), filt(consts), filt(vars), filt(funcs)
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by cmd/p6alias; DO NOT EDIT.\n\npackage %s\n\nimport %q\n\n", pkg, imp)
	for _, n := range types {
		fmt.Fprintf(&b, "type %s = %s.%s\n", n, last, n)
	}
	for _, n := range consts {
		fmt.Fprintf(&b, "const %s = %s.%s\n", n, last, n)
	}
	for _, n := range vars {
		fmt.Fprintf(&b, "var %s = %s.%s\n", n, last, n)
	}
	for _, n := range funcs {
		fmt.Fprintf(&b, "var %s = %s.%s\n", n, last, n)
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	os.WriteFile(out, src, 0o644)
}
