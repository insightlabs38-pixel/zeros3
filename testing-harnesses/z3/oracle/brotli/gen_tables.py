#!/usr/bin/env python3
"""Extracts the constant tables of the Brotli format/reference encoder from a google/brotli source
tree (v1.2.0) into brotliz3/tables_gen.go and brotliz3/brdict/dictionary.bin (the RFC 7932 static
dictionary). usage: gen_tables.py BROTLI_SRC/c Z3_DIR"""
import hashlib, re, sys, os
src, z3 = sys.argv[1], sys.argv[2]
def arr(path, name):
    s = open(os.path.join(src, path)).read()
    m = re.search(re.escape(name) + r'\s*(\[[^\]]*\])?\s*=\s*\{(.*?)\};', s, re.S)
    body = re.sub(r'/\*.*?\*/', '', m.group(2), flags=re.S)
    return [int(x, 0) for x in re.findall(r'-?(?:0x[0-9a-fA-F]+|\d+)', body)]
d = bytes(arr('common/dictionary_inc.h', 'kBrotliDictionaryData'))
assert len(d) == 122784
open(os.path.join(z3, 'brotliz3/brdict/dictionary.bin'), 'wb').write(d)
ctx = bytes(arr('common/context.c', '_kBrotliContextLookupTable'))
assert len(ctx) == 2048
frozen = bytes(arr('enc/dictionary_hash.c', 'frozen_idx'))
assert len(frozen) == 1688
t = open(os.path.join(src, 'common/transform.c')).read()
ps = ''.join(re.findall(r'"((?:[^"\\]|\\.)*)"', re.search(r'kPrefixSuffix\[217\]\s*=(.*?);', t, re.S).group(1)))
ps = ps.encode().decode('unicode_escape').encode('latin1')
ps = (ps + b'\0')[:217]  # the C array's terminating NUL is the empty affix
assert len(ps) == 217, len(ps)
psm = arr('common/transform.c', 'kPrefixSuffixMap')
m = re.search(r'kTransformsData\[\]\s*=\s*\{(.*?)\};', t, re.S).group(1)
enum = {n: i for i, n in enumerate(re.findall(r'BROTLI_TRANSFORM_[A-Z_0-9]+', re.search(r'enum BrotliWordTransformType \{(.*?)\}', open(os.path.join(src, 'common/transform.h')).read(), re.S).group(1)))}
td = [int(x) if x.isdigit() else enum[x] for x in re.findall(r'BROTLI_TRANSFORM_[A-Z_0-9]+|\d+', re.sub(r'/\*.*?\*/', '', m, flags=re.S))]
assert len(td) == 363, len(td)
log2 = [float.fromhex(float(x.rstrip('f')).hex()) for x in re.findall(r'\d+\.\d+f', open(os.path.join(src, 'enc/fast_log.c')).read())]
import struct
log2f = [struct.unpack('<f', struct.pack('<f', v))[0] for v in log2]
def hx(b): return '"' + ''.join('\\x%02x' % c for c in b) + '"'
out = ['// Code generated by oracle/brotli/gen_tables.py from google/brotli v1.2.0; DO NOT EDIT.', '', 'package brotliz3', '',
       '// DictionarySHA256 identifies the RFC 7932 static dictionary (122784 bytes).',
       'const DictionarySHA256 = "%s"' % hashlib.sha256(d).hexdigest(), '',
       'const contextLUT = ' + hx(ctx), '', 'const dictFrozenIdx = ' + hx(frozen), '',
       'const prefixSuffix = ' + hx(ps), '',
       'var prefixSuffixMap = [50]uint16{' + ', '.join(map(str, psm)) + '}', '',
       'var transformsData = [363]uint8{' + ', '.join(map(str, td)) + '}', '',
       '// log2TableBits are the float32 bit patterns of the C kBrotliLog2Table (used as a test vector).',
       'var log2TableBits = [256]uint32{' + ', '.join('0x%08x' % struct.unpack('<I', struct.pack('<f', v))[0] for v in log2f) + '}', '']
open(os.path.join(z3, 'brotliz3/tables_gen.go'), 'w').write('\n'.join(out))
print('dictionary sha256', hashlib.sha256(d).hexdigest(), 'transform enum', enum)
